"""Browser click-tests (desktop + mobile) and README screenshots.
Start the app first:  streamlit run app.py --server.port 8599   (or set APP_URL to a live URL)
Then run:             python capture_screenshots.py [--no-shots]
Needs: pip install -r requirements-dev.txt && playwright install chromium"""
import os
import re
import sys
import tempfile
from playwright.sync_api import sync_playwright

D = "docs/screenshots/"
URL = os.getenv("APP_URL", "http://localhost:8599")
SHOTS = "--no-shots" not in sys.argv
EXPECT = {"Line items": 149, "Flagged": 9, "Over-priced": 6, "Under-priced": 3, "High severity": 6}


def root(p):
    """Streamlit Cloud serves the app inside an iframe; locally it's the page itself."""
    if "streamlit.app" in URL:
        for _ in range(120):
            for f in p.frames:
                if "/~/+/" in f.url:
                    return f
            p.wait_for_timeout(1000)
        raise RuntimeError("app iframe not found")
    return p.main_frame


def settle(p, f):
    p.wait_for_timeout(1200)
    f.wait_for_function("""() => !document.body.innerText.includes('Writing reviewer note')
        && ![...document.querySelectorAll('button')].some(b => b.innerText.trim() === 'Stop')""", timeout=180000)
    p.wait_for_timeout(1200)


def no_errors(f, where):
    n = f.locator("[data-testid=stException]").count()
    assert n == 0, f"{n} exception(s): {where}"


def counter(f, label):
    return f.locator("[class*='st-key-kpi_'] button[data-testid^='stBaseButton']:visible").filter(has_text=label).first


def shown(f):
    m = re.search(r"([\d,]+) (line items|flagged|over-priced|under-priced|high severity) · net",
                  f.locator("body").inner_text())
    return int(m.group(1).replace(",", "")) if m else None


def run(p, name, mobile):
    p.goto(URL, timeout=120000)
    f = root(p)
    f.wait_for_selector("text=Cost Estimate Checker", timeout=180000)
    f.wait_for_selector("text=Generated by", timeout=180000); settle(p, f); no_errors(f, "load")
    pe = f.evaluate("getComputedStyle(document.querySelector('.hdr')).pointerEvents")
    assert pe == "none", f"header pointer-events={pe}"
    print(f"[{name}] loaded · header pointer-events:none · {f.locator('text=Generated by').first.inner_text()}")
    if SHOTS and not mobile:
        p.screenshot(path=D + "01_overview.png")

    # 1. Every counter: click, check rows + highlight
    for label, n in EXPECT.items():
        b = counter(f, label)
        b.evaluate("e => e.scrollIntoView({block: 'center'})"); p.wait_for_timeout(300)
        assert b.evaluate("""e => { const r = e.getBoundingClientRect();
            const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2);
            return !!hit && e.contains(hit); }"""), f"{label}: something is covering the counter"
        b.click(); settle(p, f); no_errors(f, label)
        kind = counter(f, label).get_attribute("data-testid") or ""
        assert "primary" in kind, f"{label} not highlighted ({kind})"
        assert shown(f) == n, f"{label}: shows {shown(f)} expected {n}"
        print(f"[{name}] counter '{label}' -> {n} rows, highlighted")
        if SHOTS and not mobile and label == "Over-priced":
            p.mouse.move(5, 5); p.wait_for_timeout(800)
            f.locator(".st-key-kpi_all").evaluate("e => e.scrollIntoView({block: 'start'})"); p.wait_for_timeout(600)
            p.screenshot(path=D + "02_counter_drilldown.png")
            f.locator(".st-key-kpi_all").evaluate("e => e.scrollIntoView({block: 'center'})"); p.wait_for_timeout(400)
        if SHOTS and mobile and label == "Flagged":
            f.locator(".st-key-kpi_all").evaluate("e => e.scrollIntoView({block: 'center'})"); p.wait_for_timeout(800)
            p.screenshot(path=D + "06_mobile.png")
    # 2. Show all reset
    counter(f, "Flagged").click(); settle(p, f)
    f.get_by_role("button", name="↺ Show all").locator("visible=true").first.click(); settle(p, f)
    assert shown(f) == 149 and "primary" in counter(f, "Line items").get_attribute("data-testid")
    print(f"[{name}] show all -> 149 rows")
    # 3. Trade filter
    counter(f, "Flagged").click(); settle(p, f)
    ms = f.locator("[data-testid=stMultiSelect]").first
    ms.evaluate("e => e.scrollIntoView({block: 'center'})"); ms.locator("input").click(); p.wait_for_timeout(800)
    f.get_by_role("option", name="Plumbing").click(); p.keyboard.press("Escape"); settle(p, f); no_errors(f, "trade")
    print(f"[{name}] trade filter Plumbing -> {shown(f)} flagged rows")
    # 4. Product card "See details" -> detail card; then table row -> detail card
    btn = f.locator("[class*='st-key-see_'] button:visible").first
    btn.evaluate("e => e.scrollIntoView({block: 'center'})"); p.wait_for_timeout(300)
    assert btn.evaluate("""e => { const r = e.getBoundingClientRect();
        const hit = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2);
        return !!hit && e.contains(hit); }"""), "something covers See details"
    btn.click(); settle(p, f)
    f.wait_for_selector(".st-key-line_detail", timeout=20000); no_errors(f, "see details")
    print(f"[{name}] See details -> detail card: {f.locator('.st-key-line_detail h4').first.inner_text()}")
    if SHOTS and not mobile:
        f.locator(".st-key-line_detail").screenshot(path=D + "03_line_detail.png")
    f.get_by_role("button", name="✕ Close details").locator("visible=true").first.click(); settle(p, f)
    f.get_by_text("See these").first.click(); p.wait_for_timeout(1500)
    grid = f.locator("[data-testid=stDataFrame]").first
    grid.scroll_into_view_if_needed(); bb = grid.bounding_box()
    p.mouse.click(bb["x"] + 18, bb["y"] + 35 + 17); settle(p, f)
    f.wait_for_selector(".st-key-line_detail", timeout=20000); no_errors(f, "row detail")
    print(f"[{name}] table row tap -> detail card")
    f.get_by_role("button", name="✕ Close details").locator("visible=true").first.click(); settle(p, f)
    f.get_by_role("button", name="↺ Show all").locator("visible=true").first.click(); settle(p, f)
    # 5. Estimate dropdown in step 3
    sb = f.locator(".stSelectbox").last
    sb.scroll_into_view_if_needed(); sb.click(); p.wait_for_timeout(600)
    f.get_by_role("option", name="EST-1002").click(); settle(p, f); no_errors(f, "selectbox")
    assert "EST-1002:" in f.locator("body").inner_text()
    print(f"[{name}] estimate dropdown -> EST-1002 · {f.locator('text=Generated by').first.inner_text()}")
    if SHOTS and not mobile:
        f.locator(".st-key-reviewer_card").screenshot(path=D + "04_ai_reviewer.png")
    # 6. Chart expander opens
    f.get_by_text("Chart: unit cost vs reference").click(); p.wait_for_timeout(2500)
    f.wait_for_selector(".js-plotly-plot", timeout=30000); no_errors(f, "chart")
    print(f"[{name}] chart expander opens")
    # 7. Upload mode: downloads + CSV/PDF upload + bad file
    f.locator("[data-testid=stButtonGroup]").get_by_text("Upload my file").click(); settle(p, f)
    for btn in ["⬇ Sample CSV", "⬇ Sample PDF"]:
        with p.expect_download(timeout=30000) as d:
            f.get_by_role("button", name=btn).click()
        print(f"[{name}] download '{btn}' -> {d.value.suggested_filename}")
    tmp = tempfile.mkdtemp(); bad = os.path.join(tmp, "wrong_cols.csv")
    open(bad, "w").write("a,b\n1,2\n")
    for path, expect in [("data/sample_estimates.csv", "Using uploaded file: sample_estimates.csv"),
                         (bad, "Missing required column"),
                         ("data/sample_estimate.pdf", "Using uploaded file: sample_estimate.pdf")]:
        f.locator("input[type=file]").set_input_files(path)
        f.wait_for_selector(f"text={expect}", timeout=90000); settle(p, f); no_errors(f, path)
        print(f"[{name}] upload {os.path.basename(path)} -> '{expect}'")
    if SHOTS and not mobile:
        p.screenshot(path=D + "05_pdf_upload.png", full_page=False)
    print(f"[{name}] ALL CLICK CHECKS PASSED")


with sync_playwright() as pw:
    b = pw.chromium.launch()
    for name, opts, mobile in [("desktop", dict(viewport={"width": 1440, "height": 1000}), False),
                               ("mobile", dict(viewport={"width": 390, "height": 844}, is_mobile=True,
                                               has_touch=True, device_scale_factor=2), True)]:
        ctx = b.new_context(accept_downloads=True, **opts)
        run(ctx.new_page(), name, mobile)
        ctx.close()
    b.close()
