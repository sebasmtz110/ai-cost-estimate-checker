"""Capture README screenshots.
Start the app first:  streamlit run app.py --server.port 8599 --server.headless true
Then run:             python capture_screenshots.py   (needs: playwright install chromium)"""
from playwright.sync_api import sync_playwright

D = "docs/screenshots/"


def settle(p):
    """Wait until Streamlit has finished running and the reviewer note is shown."""
    p.wait_for_selector("text=Generated by", timeout=120000)
    p.wait_for_timeout(1500)
    # Streamlit shows a "Stop" button and a spinner while the script is still running
    p.wait_for_function("""() => !document.body.innerText.includes('Writing reviewer note')
        && ![...document.querySelectorAll('button')].some(b => b.innerText.trim() === 'Stop')""",
                        timeout=180000)
    p.wait_for_timeout(2000)


def scroll_to(p, text):
    p.get_by_text(text).first.evaluate("e => e.scrollIntoView({block: 'start'})")
    p.wait_for_timeout(1200)


with sync_playwright() as pw:
    b = pw.chromium.launch()
    p = b.new_page(viewport={"width": 1440, "height": 1000})
    p.goto("http://localhost:8599"); settle(p)
    p.screenshot(path=D + "01_dashboard.png")
    print("reviewer source:", p.get_by_text("Generated by").first.inner_text())
    scroll_to(p, "AI reviewer summary"); p.screenshot(path=D + "02_ai_reviewer_summary.png")
    scroll_to(p, "Unit cost vs reference"); p.screenshot(path=D + "03_chart.png")
    for f, name in [("data/sample_estimates.csv", "04_csv_upload.png"),
                    ("data/sample_estimate.pdf", "05_pdf_upload.png")]:
        p.locator("input[type=file]").set_input_files(f)
        p.wait_for_selector(f"text=Using uploaded file: {f.split('/')[-1]}", timeout=60000); settle(p)
        assert p.locator("[data-testid=stException]").count() == 0, f
        scroll_to(p, "Using uploaded file"); p.screenshot(path=D + name)
        print(name, "ok; flagged:", p.locator("[data-testid=stMetricValue]").nth(1).inner_text(),
              "|", p.get_by_text("Generated by").first.inner_text())
    print("exceptions on page:", p.locator("[data-testid=stException]").count())
    b.close()
