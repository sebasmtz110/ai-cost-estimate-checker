"""Smoke tests: run with `python tests_smoke.py`. Checks the app plus the sample, CSV and PDF paths."""
import pandas as pd
from streamlit.testing.v1 import AppTest
from checker import analyze, summary
from pdf_parser import parse_pdf
from reviewer import reviewer_summary

ref = pd.read_csv("data/reference_unit_costs.csv")
PLANTED = {("EST-1002", "Asphalt shingle roofing"), ("EST-1003", "Interior paint - 2 coats"),
           ("EST-1005", "Water heater 40 gal"), ("EST-1006", "Laminate flooring install"),
           ("EST-1007", "Debris haul-off"), ("EST-1008", "Base cabinets")}

# 1. App with sample data
at = AppTest.from_file("app.py", default_timeout=120).run()
assert not at.exception, [x.value for x in at.exception]
assert any("Generated by" in m.value for m in at.markdown), "reviewer card missing"
print("app (sample data): OK, 0 exceptions")

# 2. Sample analysis finds every planted problem, rated High severity
df = analyze(pd.read_csv("data/sample_estimates.csv"), ref)
high = set(map(tuple, df[df.severity == "High"][["estimate_id", "item"]].values))
assert PLANTED <= high, PLANTED - high
print("sample: OK,", summary(df)["flagged"], "flagged; all 6 planted issues = High severity")

# 3. CSV path (single estimate subset)
csv = pd.read_csv("data/sample_estimates.csv")
out = analyze(csv[csv.estimate_id == "EST-1005"], ref)
assert out.flagged.any() and not summary(out)["peer_check_available"]
print("csv path: OK, flagged", int(out.flagged.sum()))

# 4. PDF path
pdf = parse_pdf("data/sample_estimate.pdf")
out = analyze(pdf, ref)
assert len(pdf) == 18 and out.flagged.sum() == 1
note, src = reviewer_summary(out, "EST-1002")
print(f"pdf path: OK, {len(pdf)} lines, flagged {int(out.flagged.sum())}, reviewer={src}")
print("ALL SMOKE TESTS PASSED")
