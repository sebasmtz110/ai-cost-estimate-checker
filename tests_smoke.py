"""Smoke tests: run with `python tests_smoke.py`. App (every counter, filters, show-all) + sample, CSV, PDF paths."""
import pandas as pd
from streamlit.testing.v1 import AppTest
from checker import analyze, summary
from pdf_parser import parse_pdf
from reviewer import reviewer_summary

ref = pd.read_csv("data/reference_unit_costs.csv")
PLANTED = {("EST-1002", "Asphalt shingle roofing"), ("EST-1003", "Interior paint - 2 coats"),
           ("EST-1005", "Water heater 40 gal"), ("EST-1006", "Laminate flooring install"),
           ("EST-1007", "Debris haul-off"), ("EST-1008", "Base cabinets")}
df = analyze(pd.read_csv("data/sample_estimates.csv"), ref)


def expect(d):
    return {"all": len(d), "flagged": int(d.flagged.sum()), "over": int((d.flagged & (d.direction == "HIGH")).sum()),
            "under": int((d.flagged & (d.direction == "LOW")).sum()),
            "severe": int((d.flagged & (d.severity == "High")).sum())}


def ok(at):
    assert not at.exception, [x.value for x in at.exception]


at = AppTest.from_file("app.py", default_timeout=120).run(); ok(at)
assert any("Generated by" in c.value for c in at.caption), "reviewer card missing"
assert at.session_state.view == "flagged"
for k, n in expect(df).items():
    at.button(key=f"btn_{k}").click().run(); ok(at)
    shown = len(at.dataframe[0].value)
    assert at.session_state.view == k and shown == n, (k, shown, n)
    assert at.button(key=f"btn_{k}").proto.type == "primary", f"{k} not highlighted"
    others = [o for o in expect(df) if o != k]
    assert all(at.button(key=f"btn_{o}").proto.type == "secondary" for o in others)
    print(f"counter {k}: {shown} rows, highlighted")

# Filters narrow the counters and the table
at.multiselect(key="f_trade").set_value(["Plumbing"]).run(); ok(at)
sub = df[df.category == "Plumbing"]
at.button(key="btn_all").click().run(); ok(at)
assert len(at.dataframe[0].value) == len(sub)
at.multiselect(key="f_est").set_value(["EST-1005"]).run(); ok(at)
assert len(at.dataframe[0].value) == len(sub[sub.estimate_id == "EST-1005"])
assert at.selectbox(key="estimate").value == "EST-1005", "AI reviewer should follow a single-estimate filter"
print("filters: trade + estimate narrow rows; AI reviewer follows estimate filter")
at.button(key="show_all").click().run(); ok(at)
assert at.session_state.view == "all" and not at.session_state.f_trade and len(at.dataframe[0].value) == len(df)
print("show all: resets counter + filters")

at.segmented_control(key="mode").set_value("Upload my file").run(); ok(at)
assert any("Upload a file" in i.value for i in at.info)
print("upload mode: OK")

high = set(map(tuple, df[df.severity == "High"][["estimate_id", "item"]].values))
assert PLANTED <= high, PLANTED - high
print("sample: OK,", summary(df)["flagged"], "flagged; all 6 planted issues = High severity")

csv = pd.read_csv("data/sample_estimates.csv")
out = analyze(csv[csv.estimate_id == "EST-1005"], ref)
assert out.flagged.any() and not summary(out)["peer_check_available"]
print("csv path: OK, flagged", int(out.flagged.sum()))

pdf = parse_pdf("data/sample_estimate.pdf")
out = analyze(pdf, ref)
assert len(pdf) == 18 and out.flagged.sum() == 1
note, src = reviewer_summary(out, "EST-1002")
print(f"pdf path: OK, {len(pdf)} lines, flagged {int(out.flagged.sum())}, reviewer={src}")
print("ALL SMOKE TESTS PASSED")
